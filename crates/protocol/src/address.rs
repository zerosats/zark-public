//! Isolated Zark receiving-address codec; not a Bitcoin address or signer message.
//!
//! Format 1 uses explicitly bounded, extended-length Bech32m encoding.
//! This module does not implement private handoffs,
//! claim authorization, encryption, key generation, or mainnet wallet support.
use anyhow::{Result, ensure};
use bech32::{Bech32m, ByteIterExt, Fe32, Fe32IterExt, Hrp, primitives::decode::CheckedHrpstring};
use k256::PublicKey;

pub const FORMAT_VERSION: u8 = 1;
pub const PAYLOAD_BYTES: usize = 98;
pub const MAX_ENCODED_LENGTH: usize = 170;
const PAYLOAD_SYMBOLS: usize = 157;

/// HRP classification only. The deployment digest distinguishes individual test
/// chains and protocol suites. `MainnetReserved` does not enable mainnet use.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AddressNetwork {
    Test,
    MainnetReserved,
}

impl AddressNetwork {
    pub fn hrp(self) -> &'static str {
        match self {
            Self::Test => "tzark",
            Self::MainnetReserved => "zark",
        }
    }

    pub fn encoded_length(self) -> usize {
        self.hrp().len() + 1 + 1 + PAYLOAD_SYMBOLS + 6
    }
}

/// Validated public receiving descriptor. Fields are private to preserve codec
/// invariants. It deliberately has no Display/Debug/Serialize implementation:
/// callers must explicitly encode it and must not send it to the blind signer.
#[derive(Clone, PartialEq, Eq)]
pub struct ReceivingAddress {
    network: AddressNetwork,
    deployment: [u8; 32],
    envelope_key: [u8; 33],
    claim_key: [u8; 33],
}

impl ReceivingAddress {
    /// `envelope_key` is a compressed secp256k1 ECDH public key. `claim_key` is
    /// a separate compressed, even-Y BIP340 claim-authentication public key.
    /// Both secrets must be freshly and independently generated by the wallet,
    /// separately from Bitcoin share and payout keys. This codec cannot prove
    /// secret independence, ownership, freshness, or single-use enforcement.
    pub fn new(
        network: AddressNetwork,
        deployment: [u8; 32],
        envelope_key: [u8; 33],
        claim_key: [u8; 33],
    ) -> Result<Self> {
        ensure!(deployment != [0; 32], "zero address deployment");
        ensure!(
            matches!(envelope_key[0], 2 | 3) && PublicKey::from_sec1_bytes(&envelope_key).is_ok(),
            "invalid address envelope key"
        );
        ensure!(
            claim_key[0] == 2 && PublicKey::from_sec1_bytes(&claim_key).is_ok(),
            "invalid or noncanonical address claim key"
        );
        ensure!(
            envelope_key[1..] != claim_key[1..],
            "address key roles must not use equal or negated points"
        );
        Ok(Self {
            network,
            deployment,
            envelope_key,
            claim_key,
        })
    }

    /// Parses only a canonical address for the explicitly expected deployment
    /// and network class. No unscoped parser or automatic correction is exposed.
    /// The caller must authenticate its deployment descriptor and signer trust
    /// separately; checksum validity is not recipient authentication.
    pub fn decode(
        encoded: &str,
        expected_network: AddressNetwork,
        expected_deployment: &[u8; 32],
    ) -> Result<Self> {
        ensure!(
            encoded.len() <= MAX_ENCODED_LENGTH
                && encoded.len() == expected_network.encoded_length(),
            "invalid address length"
        );
        ensure!(
            encoded
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit()),
            "address must use lowercase ASCII without whitespace"
        );
        // Bech32m alone is not sufficient: its generic decoder accepts longer
        // strings than this application's exact format and drops padding bits.
        let checked = CheckedHrpstring::new::<Bech32m>(encoded)
            .map_err(|_| anyhow::anyhow!("invalid address encoding or Bech32m checksum"))?;
        ensure!(
            checked.hrp() == Hrp::parse(expected_network.hrp())?,
            "address network mismatch"
        );
        let symbols = checked.data_part_ascii_no_checksum();
        ensure!(
            symbols.len() == 1 + PAYLOAD_SYMBOLS,
            "invalid address data length"
        );
        ensure!(
            Fe32::from_char(char::from(symbols[0]))?.to_u8() == FORMAT_VERSION,
            "unsupported address format version"
        );
        let payload_symbols: Vec<Fe32> = symbols[1..]
            .iter()
            .map(|b| Fe32::from_char(char::from(*b)))
            .collect::<std::result::Result<_, _>>()?;
        // 98*8 = 784 bits occupy 157 symbols; the final low bit must be zero.
        ensure!(
            payload_symbols[PAYLOAD_SYMBOLS - 1].to_u8() & 1 == 0,
            "noncanonical address padding"
        );
        let payload: Vec<u8> = payload_symbols.into_iter().fes_to_bytes().collect();
        ensure!(
            payload.len() == PAYLOAD_BYTES,
            "invalid address payload size"
        );
        let deployment: [u8; 32] = payload[..32].try_into()?;
        ensure!(
            deployment == *expected_deployment,
            "address deployment mismatch"
        );
        Self::new(
            expected_network,
            deployment,
            payload[32..65].try_into()?,
            payload[65..98].try_into()?,
        )
    }

    /// Explicitly renders the public descriptor for confidential, authenticated
    /// delivery to the sender. The output is always lowercase.
    pub fn encode(&self) -> String {
        let mut payload = [0; PAYLOAD_BYTES];
        payload[..32].copy_from_slice(&self.deployment);
        payload[32..65].copy_from_slice(&self.envelope_key);
        payload[65..].copy_from_slice(&self.claim_key);
        let hrp = Hrp::parse(self.network.hrp()).expect("fixed valid address HRP");
        std::iter::once(Fe32::try_from(FORMAT_VERSION).expect("fixed valid address version"))
            .chain(payload.iter().copied().bytes_to_fes())
            .with_checksum::<Bech32m>(&hrp)
            .chars()
            .collect()
    }

    pub fn network(&self) -> AddressNetwork {
        self.network
    }

    pub fn deployment(&self) -> &[u8; 32] {
        &self.deployment
    }

    pub fn envelope_key(&self) -> &[u8; 33] {
        &self.envelope_key
    }

    pub fn claim_key(&self) -> &[u8; 33] {
        &self.claim_key
    }
}
